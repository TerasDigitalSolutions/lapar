import { createHash } from 'node:crypto';
import { readdirSync } from 'node:fs';
import { join, relative } from 'node:path';
import type { Plugin } from 'vite';

type Chunk = {
  fileName: string;
  imports: string[];
  dynamicImports: string[];
  facadeModuleId: string | null;
  moduleIds?: string[];
  modules: Record<string, unknown>;
  viteMetadata?: { importedCss: Set<string>; importedAssets: Set<string> };
};

const SUPABASE = /[\\/]node_modules[\\/]@supabase[\\/]/;
const norm = (p: string) => p.replace(/\\/g, '/');

function walk(start: Chunk, byName: Record<string, Chunk>, withDynamic: boolean): Chunk[] {
  const seen = new Set<string>();
  const stack = [start];
  while (stack.length) {
    const c = stack.pop()!;
    if (seen.has(c.fileName)) continue;
    seen.add(c.fileName);
    for (const f of withDynamic ? [...c.imports, ...c.dynamicImports] : c.imports) {
      const n = byName[f];
      if (n) stack.push(n);
    }
  }
  return [...seen].map((f) => byName[f]!);
}

const withSupabase = (chunks: Chunk[]) =>
  chunks.filter((c) => (c.moduleIds ?? Object.keys(c.modules)).some((m) => SUPABASE.test(m)));

const workerSource = (cache: string, list: string[], scope: string, shell: string) => `// Generated by build/demo-sw-plugin.ts
const CACHE = ${JSON.stringify(cache)};
const LIST = ${JSON.stringify(list)};
const SCOPE = ${JSON.stringify(scope)};
const SHELL = ${JSON.stringify(shell)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(LIST)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((ks) => Promise.all(ks.filter((k) => k.startsWith('lapar-demo-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (e) => {
  const r = e.request;
  const url = new URL(r.url);
  if (r.method !== 'GET' || url.origin !== self.location.origin) return;
  if (r.mode === 'navigate' && url.pathname.startsWith(SCOPE)) {
    e.respondWith(caches.match(SHELL).then((m) => m || fetch(r)));
  } else if (LIST.includes(url.pathname)) {
    e.respondWith(caches.match(url.pathname).then((m) => m || fetch(r)));
  }
});
`;

export function demoSwPlugin(): Plugin {
  let base = '/';
  let publicDir = '';
  return {
    name: 'lapar-demo-sw',
    apply: 'build',
    enforce: 'post',
    configResolved(c) {
      base = c.base;
      publicDir = c.publicDir;
    },
    generateBundle(_o, bundle) {
      const chunks = Object.values(bundle).filter((b) => b.type === 'chunk') as unknown as Chunk[];
      const byName = Object.fromEntries(chunks.map((c) => [c.fileName, c]));
      const entry = (suffix: string) => chunks.find((c) => c.facadeModuleId && norm(c.facadeModuleId).endsWith(suffix));

      const demoEntry = entry('/app/demo/index.html');
      if (!demoEntry) this.error('[demo-guard] demo entry chunk not found (facadeModuleId)');
      const demo = walk(demoEntry, byName, true);

      const customerEntry = entry('/app/src/features/customer/index.tsx');
      if (!customerEntry) this.error('[demo-guard] customer route chunk not found (facadeModuleId)');
      const customer = walk(customerEntry, byName, false);

      for (const [name, cs] of [['demo', demo], ['customer route static', customer]] as const) {
        const hit = withSupabase(cs);
        if (hit.length) this.error(`[demo-guard] @supabase reaches the ${name} bundle via: ${hit.map((c) => c.fileName).join(', ')}`);
      }

      console.log(
        `[demo-guard] demo chunks=${demo.length} supabase=0; customer static chunks=${customer.length} supabase=0; app supabase modules=${withSupabase(chunks).length}`,
      );

      const files = new Set<string>(['demo/index.html']);
      for (const c of demo) {
        files.add(c.fileName);
        c.viteMetadata?.importedCss.forEach((f) => files.add(f));
        c.viteMetadata?.importedAssets.forEach((f) => files.add(f));
      }
      const demoPublic = join(publicDir, 'demo');
      const pub = (d: string): string[] =>
        readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? pub(join(d, e.name)) : [join(d, e.name)]));
      for (const f of pub(demoPublic)) files.add('demo/' + norm(relative(demoPublic, f)));
      files.delete('demo/sw.js');

      const list = [...files].sort().map((f) => base + f);
      const cache = 'lapar-demo-' + createHash('sha256').update(list.join('\n')).digest('hex').slice(0, 8);
      this.emitFile({
        type: 'asset',
        fileName: 'demo/sw.js',
        source: workerSource(cache, list, base + 'demo/', base + 'demo/index.html'),
      });
    },
  };
}
